"""Compose workspace manifests and delivery policy from module declarations."""

import json
import os
from pathlib import Path
import re
import tomllib

from .model import relative
from .toml import dumps



def toml_document(value):
    return "# Generated by make prepare; edit the owning component.json or policy template.\n" + dumps(value)


def declarations(modules):
    for module in sorted(modules.values(), key=lambda m: m.name):
        for artifact in module.metadata.get('artifacts', []):
            if not isinstance(artifact, dict):
                raise ValueError(f'{module.name}: artifact must be an object')
            kinds = [kind for kind in ('binary', 'library', 'source', 'symlink') if kind in artifact]
            if len(kinds) != 1:
                raise ValueError(f'{module.name}: artifact must have exactly one delivery kind')
            relative(artifact['destination'])
            if artifact.get('environment', 'system') not in ('boot', 'system'):
                raise ValueError(f'{module.name}: unsupported artifact environment')
            yield module, artifact, kinds[0]


def symbol(artifact):
    scope = 'BOOT' if artifact.get('environment') == 'boot' else 'SYSTEM'
    return scope + '_APP_' + re.sub(r'[^A-Za-z0-9]', '_', artifact['staged']).upper()


def product_schema(modules, policy):
    programs = {(m.name, a['staged']): a for m, a, kind in declarations(modules) if kind == 'binary'}
    names, destinations = set(), set()
    lines = ['# Generated from repository artifact declarations.',
             'mainmenu "HypeR System Configuration"', '']
    for module in sorted(modules.values(), key=lambda m: m.name):
        entries = [a for m, a, kind in declarations({module.name: module}) if kind == 'binary']
        if not entries:
            continue
        lines.extend(('menu ' + json.dumps(module.name), ''))
        for artifact in entries:
            name = symbol(artifact)
            destination = artifact.get('environment', 'system'), artifact['destination']
            if name in names or destination in destinations:
                raise ValueError(f'duplicate installed program: {module.name}/{artifact["staged"]}')
            names.add(name)
            destinations.add(destination)
            enabled = artifact.get('enabled', False)
            if not isinstance(enabled, bool):
                raise ValueError(f'{module.name}: artifact enabled must be boolean')
            prompt = f'{artifact["staged"]} (/{artifact["destination"]})'
            lines.extend(('config ' + name, '    bool ' + json.dumps(prompt),
                          '    default ' + ('y' if enabled else 'n')))
            dependencies = []
            for dependency in artifact.get('requires', []):
                target = programs.get((dependency['module'], dependency['artifact']))
                if target is None or target.get('environment', 'system') != artifact.get('environment', 'system'):
                    raise ValueError(f'{module.name}: invalid runtime dependency {dependency}')
                dependencies.append(symbol(target))
            if dependencies:
                lines.append('    depends on ' + ' && '.join(dependencies))
            lines.extend(('    help', f'        Build and install {artifact["binary"]} from {module.name}.', ''))
        lines.extend(('endmenu', ''))
    return '\n'.join(lines) + '\n' + policy


def records(modules):
    """Use the existing delivery validator with metadata-owned declarations."""
    for module, artifact, kind in declarations(modules):
        profiles = ' '.join(artifact.get('profiles', []))
        if kind in ('binary', 'library'):
            manifest = relative(artifact['manifest'])
            source = str(module.path / manifest.parent)
            fields = [kind, source, artifact[kind], artifact['staged'], artifact['destination'], profiles,
                      artifact.get('rust_runtime', 'std'), artifact.get('mode', '0755'),
                      artifact.get('environment', 'system')]
        else:
            source = artifact[kind]
            if kind == 'source' and not source.startswith('{'):
                source = str(module.path / relative(source))
            fields = [kind, source, artifact['destination'], artifact.get('mode', '0644'), profiles,
                      artifact.get('environment', 'system')]
        if any(not isinstance(value, str) or any(c in value for c in '\n\r|') for value in fields):
            raise ValueError(f'{module.name}: invalid artifact record')
        yield '|'.join(fields)


def cargo_manifests(modules, templates):
    result = {}
    for domain, definition in templates.items():
        owner = modules[definition['module']]
        data = tomllib.loads((owner.source / relative(definition['template'])).read_text())
        directory = relative(definition['directory'])
        members, providers = [], {}
        for module in modules.values():
            for entry in module.metadata.get('cargo', []):
                if entry['domain'] != domain:
                    continue
                manifest = relative(entry['manifest'])
                source = module.source / manifest
                package = tomllib.loads(source.read_text())['package']
                path = module.path / manifest.parent
                members.append(os.path.relpath(path, directory))
                name = package['name']
                if name in providers:
                    raise ValueError(f'duplicate Cargo package in {domain}: {name}')
                providers[name] = path
        data['workspace']['members'] = sorted(members)
        for name, value in data['workspace'].get('dependencies', {}).items():
            if isinstance(value, dict) and 'path' in value:
                package = value.get('package', name)
                if package not in providers:
                    raise ValueError(f'{domain}: missing workspace dependency provider {package}')
                value['path'] = os.path.relpath(providers[package], directory)
        result[str(directory / 'Cargo.toml')] = toml_document(data)
    return result
